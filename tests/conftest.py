    """
    2 s of 440 Hz stereo at 44.1 kHz, generated by ffmpeg: everything the audio
    extraction has to convert. ffmpeg is required, not skipped: CI installs it.
    """
    path = tmp_path / "sine.wav"
    subprocess.run(
        [shutil.which("ffmpeg") or "ffmpeg", "-hide_banner", "-loglevel", "error", "-f", "lavfi",
         "-i", "sine=frequency=440:duration=2", "-ac", "2", "-ar", "44100", str(path)],
        check=True,
    )
    return path


